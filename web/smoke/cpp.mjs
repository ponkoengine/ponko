#!/usr/bin/env node
// A C++ game in the browser (the web guide's "C and C++"): the
// getting-started game of the guide, the `first_game_full` snippet of
// examples/cpp/guide.cpp exactly as the guide shows it, built with
// web/build-cpp.sh and run in headless Chromium (no window). It must:
//
// 1. start: the page's status line goes away (the game reached its event
//    loop) with no page error;
// 2. fetch `crab.png` (HTTP 200), which its setup loads;
// 3. draw: the canvas is not blank (the crab on the clear color), on WebGL2;
// 4. keep running its C++ systems: while ArrowRight is held the crab moves
//    right. The system is a lambda capturing `pos`, a local of the game's
//    function, by reference: the local must outlive the call to run(),
//    which in a browser doesn't return.
//
//   node web/smoke/cpp.mjs --build          # build target/web/first_game, then run it
//   node web/smoke/cpp.mjs [--dir <site>] [--out <dir>] [--timeout <s>]
//
// The report (report.json in --out) has the module's size and the startup
// time (navigation to the game's first frame); --out also gets the canvas
// before and after the key (before.png, after.png). Exit codes as smoke.mjs: 0
// passed, 1 failed, 2 unsupported (no browser), 3 bad arguments or no build.

import { spawnSync } from "node:child_process";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { EXIT, UsageError, launchConfig, launchFailureKind, withDeadline } from "./lib.mjs";
import { GAME_CANVAS, LAUNCHERS, serve } from "./smoke.mjs";

const here = fileURLToPath(new URL(".", import.meta.url));
const repo = resolve(here, "../..");

/** The lines of `source` between `ANCHOR: name` and `ANCHOR_END: name`. */
export function anchored(source, name) {
  const lines = source.split("\n");
  const start = lines.findIndex((l) => l.trim() === `// ANCHOR: ${name}`);
  const end = lines.findIndex((l) => l.trim() === `// ANCHOR_END: ${name}`);
  if (start < 0 || end <= start) throw new Error(`no anchor ${name}`);
  return lines.slice(start + 1, end).join("\n");
}

/** The guide's first game as a program: its snippet and a main that plays it. */
export function firstGameProgram(guide) {
  return [
    "// Generated by web/smoke/cpp.mjs from examples/cpp/guide.cpp (first_game_full).",
    '#include "ponko.hpp"',
    anchored(guide, "first_game_full"),
    "int main() { my_game(); }",
    "",
  ].join("\n");
}

/**
 * The bounding box of the pixels unlike the most common color (the clear
 * color) in a PNG screenshot, decoded in the page: null when there are none.
 */
async function foreground(page, png) {
  return page.evaluate(async (base64) => {
    const image = new Image();
    image.src = `data:image/png;base64,${base64}`;
    await image.decode();
    const canvas = document.createElement("canvas");
    canvas.width = image.width;
    canvas.height = image.height;
    const ctx = canvas.getContext("2d");
    ctx.drawImage(image, 0, 0);
    const { data } = ctx.getImageData(0, 0, image.width, image.height);
    const counts = new Map();
    for (let i = 0; i < data.length; i += 4) {
      const key = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2];
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
    let background = 0;
    let most = 0;
    for (const [key, n] of counts) if (n > most) [background, most] = [key, n];
    let box = null;
    for (let y = 0; y < image.height; y++) {
      for (let x = 0; x < image.width; x++) {
        const i = (y * image.width + x) * 4;
        if (((data[i] << 16) | (data[i + 1] << 8) | data[i + 2]) === background) continue;
        box ??= { left: x, right: x, top: y, bottom: y };
        box.left = Math.min(box.left, x);
        box.right = Math.max(box.right, x);
        box.top = Math.min(box.top, y);
        box.bottom = Math.max(box.bottom, y);
      }
    }
    return box && { ...box, centerX: (box.left + box.right) / 2, colors: counts.size };
  }, png.toString("base64"));
}

function parseArgs(argv) {
  const args = { dir: join(repo, "target/web/first_game"), out: join(repo, "target/web-smoke/cpp"), build: false, timeout: 60 };
  for (let i = 0; i < argv.length; i++) {
    const value = () => {
      if (argv[i + 1] === undefined) throw new UsageError(`${argv[i]} needs a value`);
      return argv[++i];
    };
    switch (argv[i]) {
      case "--dir": args.dir = resolve(value()); break;
      case "--out": args.out = resolve(value()); break;
      case "--timeout": args.timeout = Number(value()); break;
      case "--build": args.build = true; break;
      default: throw new UsageError(`unknown argument ${argv[i]}`);
    }
  }
  return args;
}

/** Builds the guide's first game into `dir` with web/build-cpp.sh, from the repository (its assets). */
async function build(dir) {
  const source = join(repo, "target/web-cpp-src/first_game.cpp");
  await mkdir(join(repo, "target/web-cpp-src"), { recursive: true });
  await writeFile(source, firstGameProgram(await readFile(join(repo, "examples/cpp/guide.cpp"), "utf8")));
  const result = spawnSync("bash", [join(repo, "web/build-cpp.sh"), "-o", dir, source], { cwd: repo, stdio: "inherit" });
  if (result.status !== 0) throw new UsageError(`web/build-cpp.sh failed (exit ${result.status})`);
}

async function main() {
  let args;
  try {
    args = parseArgs(process.argv.slice(2));
    if (args.build) await build(args.dir);
    await stat(join(args.dir, "game_bg.wasm"));
  } catch (e) {
    console.error(e instanceof UsageError ? e.message : `no build in ${args?.dir}: run with --build (${e.message})`);
    process.exit(EXIT.usage);
  }
  await mkdir(args.out, { recursive: true });
  const wasm = await readFile(join(args.dir, "game_bg.wasm"));
  const report = { wasmBytes: wasm.length, wasmGzipBytes: gzipSync(wasm, { level: 9 }).length, steps: [] };
  const finish = async (code, message) => {
    report.result = message;
    await writeFile(join(args.out, "report.json"), JSON.stringify(report, null, 2) + "\n");
    console.log(`${code === EXIT.pass ? "PASS" : code === EXIT.unsupported ? "UNSUPPORTED" : "FAIL"}: ${message}`);
    console.log(JSON.stringify(report));
    process.exit(code);
  };

  const server = await serve(args.dir);
  const url = `http://127.0.0.1:${server.address().port}/`;
  let browser;
  try {
    browser = await LAUNCHERS.chromium.launch(launchConfig("chromium", process.platform).options);
  } catch (e) {
    server.close();
    const kind = launchFailureKind(String(e.message), process.env);
    return finish(kind === "unsupported" ? EXIT.unsupported : EXIT.app, `could not start Chromium: ${e.message}`);
  }
  const deadline = args.timeout * 1000;
  try {
    const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
    // WebGL2, as the other runners' headless checks: the headless shell's
    // WebGPU device can't present a canvas (see README.md, "What runs where").
    await page.addInitScript(() => {
      Object.defineProperty(Navigator.prototype, "gpu", { get: () => undefined, configurable: true });
    });
    const errors = [];
    const console_ = [];
    const fetched = new Map();
    page.on("pageerror", (e) => errors.push(String(e)));
    page.on("console", (m) => console_.push(`${m.type()}: ${m.text()}`));
    page.on("response", (r) => fetched.set(new URL(r.url()).pathname, r.status()));
    report.console = console_;

    await withDeadline(page.goto(url), deadline, "loading the page");
    // 1. Started: the template removes its status line when the game's
    // first frame is ready, and shows an error in it otherwise.
    await withDeadline(
      page.waitForFunction(() => !document.getElementById("status")?.isConnected || document.getElementById("status").className === "error", null, { timeout: deadline, polling: 16 }),
      deadline + 1000,
      "the game's start",
    );
    const status = await page.evaluate(() => {
      const s = document.getElementById("status");
      return s?.isConnected ? s.textContent : null;
    });
    if (status !== null) return finish(EXIT.app, `the game didn't start: ${status}`);
    report.startupMs = Math.round(await page.evaluate(() => performance.now()));
    report.steps.push("started");

    // 2. Its texture.
    if (fetched.get("/assets/crab.png") !== 200) return finish(EXIT.app, `crab.png not fetched: ${fetched.get("/assets/crab.png") ?? "no request"}`);
    report.steps.push("crab.png fetched");

    // 3. Drawn.
    await page.waitForTimeout(500);
    const canvas = page.locator(GAME_CANVAS);
    const beforePng = await canvas.screenshot({ path: join(args.out, "before.png") });
    const before = await foreground(page, beforePng);
    report.before = before;
    if (!before) return finish(EXIT.app, "the canvas is blank");
    report.steps.push("drawn");

    // 4. The systems run and see the keys: hold ArrowRight.
    await canvas.click({ position: { x: 5, y: 5 } });
    await page.keyboard.down("ArrowRight");
    await page.waitForTimeout(1000);
    await page.keyboard.up("ArrowRight");
    await page.waitForTimeout(200);
    const after = await foreground(page, await canvas.screenshot({ path: join(args.out, "after.png") }));
    report.after = after;
    if (!after || after.centerX < before.centerX + 20) {
      return finish(EXIT.app, `the crab didn't move right while ArrowRight was held: ${JSON.stringify({ before, after })}`);
    }
    report.steps.push("moved right");
    if (errors.length) return finish(EXIT.app, `page errors: ${errors.join("; ")}`);
    return finish(EXIT.pass, `the guide's C++ game ran: started in ${report.startupMs} ms, ${report.wasmBytes} bytes of wasm`);
  } catch (e) {
    return finish(EXIT.app, String(e.message ?? e));
  } finally {
    await browser.close().catch(() => {});
    server.close();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
