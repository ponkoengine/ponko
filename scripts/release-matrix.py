#!/usr/bin/env python3
"""The release-time OS matrix: a GitHub Actions workflow made from checks.yml.

    release-matrix.py write    # regenerate scripts/release-matrix.yml
    release-matrix.py check    # fail if it is out of date with checks.yml
    release-matrix.py selftest

The project has no CI (CONTRIBUTING.md, "Releasing"). Once per minor release
the maintainers may run the checks that need three operating systems on
hosted runners, at the cut, instead of on their own machines. This script
writes that workflow, `scripts/release-matrix.yml`, from the jobs of
`scripts/checks.yml`, so the two cannot drift apart. The file is NOT
enabled: it lives under scripts/, which GitHub never reads. It runs only when
a maintainer, at the cut, turns Actions on, puts it on a branch of its own
and pushes it:

    git switch --detach v0.2.0-rc.1
    mkdir -p .github/workflows && cp scripts/release-matrix.yml .github/workflows/
    git switch -c release-matrix/checks-0.2.0-rc.1
    git add .github/workflows/release-matrix.yml && git commit -m "Release matrix"
    git push origin release-matrix/checks-0.2.0-rc.1

The branch name picks the jobs: `release-matrix/checks-<version>` runs the
checks, `release-matrix/first-run-<version>` (pushed after `cargo publish`)
runs scripts/first-run.py on each OS against crates.io. Delete the branch
afterwards and turn Actions off again. Nothing here touches `main`.

What changes from checks.yml: the `local-*` keys are dropped (only
run-checks.py reads them), the removed local actions
(`./.github/actions/windows-linker` and `nextest`) become inline steps that do
the same, and a trigger, a
concurrency group and the first-run job are added.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CHECKS = os.path.join(HERE, "checks.yml")
OUT = os.path.join(HERE, "release-matrix.yml")

# The checks that need more than one OS, or the hosted runner's clean
# machine: every test lane, the C/C++ programs, the packaged game and the
# project templates. The single-OS checks (formatting, clippy, the book,
# semver, the web smoke runs) stay on the maintainers' machines.
JOBS = (
    "test",
    "windows-unit-build",
    "windows-unit",
    "test-features",
    "native",
    "package-smoke",
    "templates",
)

LOCAL_KEY = re.compile(r"^\s+(- )?local-[a-z]+:")
JOB_KEY = re.compile(r"^  ([a-z0-9-]+):\s*$")
LOCAL_ACTION = re.compile(r"^(\s*)- uses: \./\.github/actions/([a-z-]+)\s*$")

HEADER = """\
# GENERATED by scripts/release-matrix.py from scripts/checks.yml: do not edit.
#
# NOT ENABLED. The release-time OS matrix, run once per minor release at the
# cut (CONTRIBUTING.md, "Releasing"). GitHub never reads scripts/; to run it,
# a maintainer copies it to .github/workflows/ on a branch of its own,
# `release-matrix/checks-<version>` or `release-matrix/first-run-<version>`,
# pushes that branch and deletes it afterwards (scripts/release-matrix.py has
# the commands). Never merge it into main.
name: Release matrix

on:
  push:
    branches: ["release-matrix/**"]

concurrency:
  group: release-matrix-${{ github.ref }}
  cancel-in-progress: true

permissions:
  contents: read
"""

FIRST_RUN = """\
  # After `cargo publish`: a new user's first run from crates.io on each OS
  # (scripts/first-run.py; the version is the branch name's suffix).
  first-run:
    if: startsWith(github.ref_name, 'release-matrix/first-run-')
    name: First run from crates.io (${{ matrix.os }})
    runs-on: ${{ matrix.os }}
    timeout-minutes: 90
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, macos-latest, windows-latest]
    steps:
      - uses: actions/checkout@v7
        with:
          sparse-checkout: |
            scripts/first-run.py
            book/src/getting-started.md
          sparse-checkout-cone-mode: false
      - name: Install ALSA and udev headers (audio, gamepads)
        if: runner.os == 'Linux'
        run: sudo apt-get install -y libasound2-dev libudev-dev
      - uses: dtolnay/rust-toolchain@stable
      - name: First run
        shell: bash
        run: |
          version="${GITHUB_REF_NAME#release-matrix/first-run-}"
          cp scripts/first-run.py "$RUNNER_TEMP/"
          cd "$RUNNER_TEMP"
          python3 first-run.py "$version" --dir "$RUNNER_TEMP/first-run"
"""


def nextest(indent):
    """The removed `nextest` action: the pinned test runner, installed."""
    return [
        f"{indent}- uses: taiki-e/install-action@v2",
        f"{indent}  with:",
        f"{indent}    tool: nextest@0.9.151",
    ]


def windows_linker(indent):
    """The removed composite action, as one inline step at `indent`."""
    body = [
        "$sysroot = rustc --print sysroot",
        "if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }",
        "$linker = Join-Path $sysroot 'lib/rustlib/x86_64-pc-windows-msvc/bin/rust-lld.exe'",
        "if (!(Test-Path $linker)) { throw \"Rust's bundled linker is missing: $linker\" }",
        "& $linker -flavor link --version",
        "if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }",
        '"CARGO_TARGET_X86_64_PC_WINDOWS_MSVC_LINKER=$linker" >> $env:GITHUB_ENV',
    ]
    lines = [
        f"{indent}- name: Windows linker (the LLD bundled with the Rust toolchain)",
        f"{indent}  shell: pwsh",
        f"{indent}  run: |",
    ]
    return lines + [f"{indent}    {line}" for line in body]


# The composite actions checks.yml still names, which went with .github/.
LOCAL_ACTIONS = {"nextest": nextest, "windows-linker": windows_linker}


def top_level(text, key):
    """The lines of a top-level mapping `key:` (without the key line)."""
    lines = text.splitlines()
    start = lines.index(f"{key}:")
    block = []
    for line in lines[start + 1:]:
        if line and not line.startswith((" ", "#")):
            break
        block.append(line)
    while block and not block[-1].strip():
        block.pop()
    return block


def jobs(text):
    """{job name: its lines}, comments above a job going with it."""
    lines = text.splitlines()
    start = lines.index("jobs:") + 1
    found, name, pending = {}, None, []
    for line in lines[start:]:
        m = JOB_KEY.match(line)
        if m:
            name = m.group(1)
            found[name] = pending + [line]
            pending = []
        elif line.startswith("  #") or not line.strip():
            pending.append(line)
        elif name:
            found[name] += pending + [line]
            pending = []
    for body in found.values():
        while body and not body[-1].strip():
            body.pop()
    return found


def convert(job_lines, name):
    out = []
    for line in job_lines:
        if LOCAL_KEY.match(line):
            if line.lstrip().startswith("- "):
                raise SystemExit(f"release-matrix: {name}: a step that starts with a local-* key")
            continue
        m = LOCAL_ACTION.match(line)
        if m and m.group(2) in LOCAL_ACTIONS:
            out += LOCAL_ACTIONS[m.group(2)](m.group(1))
            continue
        if "./.github/" in line:
            raise SystemExit(f"release-matrix: {name}: a local action GitHub no longer has: {line.strip()}")
        out.append(line)
    # The checks run on the checks branch only.
    head = next(i for i, line in enumerate(out) if JOB_KEY.match(line))
    out.insert(head + 1, "    if: startsWith(github.ref_name, 'release-matrix/checks-')")
    return out


def generate(text):
    found = jobs(text)
    missing = [j for j in JOBS if j not in found]
    if missing:
        raise SystemExit(f"release-matrix: checks.yml has no job {', '.join(missing)}")
    for job in JOBS:
        for need in re.findall(r"^    needs: ([a-z0-9-]+)", "\n".join(found[job]), re.M):
            if need not in JOBS:
                raise SystemExit(f"release-matrix: {job} needs {need}, which is not in JOBS")
    parts = [HEADER, "env:", *top_level(text, "env"), "", "jobs:"]
    for job in JOBS:
        parts += convert(found[job], job) + [""]
    return "\n".join(parts) + FIRST_RUN


def selftest():
    sample = """\
env:
  A: "1"
  # comment
  B: two

jobs:
  # The first job.
  one:
    local-os: [Linux]
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v7
      - name: Step
        local-skip: Hosted only.
        run: echo one
      - uses: ./.github/actions/windows-linker
        if: runner.os == 'Windows'

  two:
    needs: one
    runs-on: windows-latest
    steps:
      - run: echo two
"""
    found = jobs(sample)
    assert list(found) == ["one", "two"], found
    assert found["one"][0] == "  # The first job.", found["one"]
    assert top_level(sample, "env") == ['  A: "1"', "  # comment", "  B: two"]
    one = convert(found["one"], "one")
    assert not any("local-" in line for line in one), one
    assert "    if: startsWith(github.ref_name, 'release-matrix/checks-')" == one[2], one
    i = one.index("      - name: Windows linker (the LLD bundled with the Rust toolchain)")
    assert one[i + 1] == "        shell: pwsh" and one[-1] == "        if: runner.os == 'Windows'", one
    assert convert(["  x:", "      - uses: ./.github/actions/nextest"], "x")[2:] == nextest("      ")
    try:
        convert(["  x:", "      - uses: ./.github/actions/other"], "x")
        raise AssertionError("a missing local action passed")
    except SystemExit as e:
        assert "no longer has" in str(e)
    with open(CHECKS, encoding="utf-8") as f:
        real = generate(f.read())
    assert "local-" not in real and "./.github/" not in real
    assert real.count("if: startsWith(github.ref_name, 'release-matrix/checks-')") == len(JOBS)
    print("release-matrix.py selftest: ok")


def main():
    cmd = sys.argv[1:] or ["check"]
    if cmd == ["selftest"]:
        return selftest()
    with open(CHECKS, encoding="utf-8") as f:
        text = generate(f.read())
    if cmd == ["write"]:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
    elif cmd == ["check"]:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            raise SystemExit("release-matrix.yml is out of date with checks.yml: "
                             "run python3 scripts/release-matrix.py write")
        print("release-matrix.yml matches checks.yml")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
