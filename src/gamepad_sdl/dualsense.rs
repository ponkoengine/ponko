    // The same reference mapping that SDL_SetGamepadPlayerIndex uses on
    // DualSense. As with light color, SDL owns the payload and framing.
    fn player_report(player: Option<usize>) -> Payload {
        const PATTERNS: [u8; 7] = [0x04, 0x0a, 0x15, 0x1b, 0x1f, 0x11, 0x0e];
        let mut data = [0; PAYLOAD_SIZE];
        data[1] = 1 << 4;
        data[43] = player.map_or(0, |n| 0x20 | PATTERNS[n % PATTERNS.len()]);
        data
    }

